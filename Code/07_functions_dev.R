# This code will develop user based functions 

summa <- function(num1,num2){
  z = num1 + num2
  return(z)
  }
summa(3, 5)

# Exercise: build a function to multiply (*) two numbers 
multi <- function(num1,num2){
  z = num1 * num2
  return(z)
  }
multi(3, 4)

